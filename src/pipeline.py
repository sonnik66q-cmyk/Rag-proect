# Функция для чтения системного промпта (правил для нейросети) из текстового файла
def get_system_prompt(): 
    # Формируем путь к файлу: папка "prompts" и файл "system.txt"
    prompt_path = os.path.join("prompts", "system.txt") 
    # Проверяем, существует ли такой файл на диске
    if os.path.exists(prompt_path): 
        # Открываем файл в режиме чтения с кодировкой UTF-8 (чтобы русские буквы читались правильно)
        with open(prompt_path, "r", encoding="utf-8") as f: 
            # Читаем всё содержимое файла и возвращаем его
            return f.read() 
    # Если файла нет, возвращаем базовый промпт по умолчанию
    else: 
        return "Ты — ИИ-ассистент. Отвечай строго по контексту. Если ответа нет, скажи: «В моей базе знаний нет информации»."

# Главная функция для обработки вопроса пользователя
# question - текст вопроса, k - количество кусков текста для поиска
def ask(question: str, k: int = 7): 
 
    # Блок try нужен, чтобы программа не упала, если база данных пуста или не сработал эмбеддер
    try: 
        # Превращаем текст вопроса в вектор (массив чисел) с помощью нейросети-эмбеддера
        # [0] берет первый элемент, так как embed возвращает список векторов
        q_vec = embed([question])[0] 
        # Ищем в базе данных k самых похожих кусков текста на наш вектор
        hits = search(q_vec, k=k) 
    # Если произошла ошибка при поиске, перехватываем её
    except Exception as e: 
        # Выводим сообщение об ошибке и прерываем выполнение функции
        print(f"Ошибка поиска в базе: {e}") 
        return

    # Склеиваем все найденные куски текста в одну большую строку
    # Для каждого куска пишем номер страницы и сам текст
    context = "\n\n".join(f"[стр. {h['page']}] {h['text']}" for h in hits) 
    # Загружаем правила для нейросети из файла
    system_prompt = get_system_prompt() 

    # Формируем список сообщений для нейросети
    messages = [ 
        # Первое сообщение - роль "system" (системные правила). Сюда передаем промпт
        {"role": "system", "content": system_prompt}, 
        # Второе сообщение - роль "user" (пользователь). Передаем контекст и сам вопрос
        {"role": "user", "content": f"Контекст из документа:\n{context}\n\nВопрос: {question}"} 
    ] 
    
    # Отправляем подготовленные сообщения в функцию работы с нейросетью
    answer = ask_gigachat(messages) 
    
    # Выводим готовый ответ на экран, делая отступ сверху для красоты
    print(f"\nОтвет: {answer}") 
    
    # Возвращаем ответ из функции (может пригодиться для тестов)
    return answer 

# Функция для автоматического тестирования (демо)
